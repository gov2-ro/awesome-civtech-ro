"""Draw the complete draft vocabulary as readable Mermaid diagrams. Stdlib only.

Run from any directory:
    python3 data/taxonomy-v2/export_mermaid.py

Only writes docs/specs/taxonomy-v2-vocabulary.md. Does not alter data or the public site.
"""
import csv
import html
from pathlib import Path

HERE = Path(__file__).resolve().parent
TARGET = HERE.parents[1] / 'docs/specs/taxonomy-v2-vocabulary.md'
TITLES = {
    'scop': 'Scopuri civice',
    'functie': 'Funcționalități și activități',
    'format': 'Formate',
    'tehnologie': 'Tehnologii',
    'institutie': 'Instituții vizate',
    'organizatie': 'Tipuri de organizație',
    'maturitate': 'Maturitate',
}


def main():
    with (HERE / 'concepte.csv').open(encoding='utf-8-sig', newline='') as stream:
        rows = list(csv.DictReader(stream))
    by_id = {r['id']: r for r in rows}
    if len(rows) != len(by_id):
        raise SystemExit('Duplicate concept IDs: validate the concept table first.')
    for row in rows:
        for parent in filter(None, row['mai_larg'].split('|')):
            if parent not in by_id:
                raise SystemExit(f'Unknown broader concept: {parent}')
    # Row-independent Mermaid node identifiers. The original ID remains in each label.
    node_ids = {r['id']: 'c_' + r['id'].replace(':', '_').replace('-', '_') for r in rows}
    if len(set(node_ids.values())) != len(node_ids):
        raise SystemExit('Mermaid node identifier collision.')
    drawn = set()
    chunks = [
        '# Taxonomy v2 — complete vocabulary diagrams\n',
        'Generated from `data/taxonomy-v2/concepte.csv`. Do not edit this file by hand.\n',
        f'This snapshot contains **{len(rows)} concepts**. Every concept is included below.\n',
        'Labels and IDs are shown together for editorial review. All concepts remain proposals unless accepted in the source table.\n',
        'Arrows run from broader to narrower concepts. Related-concept links and external mappings are omitted from these hierarchy views.\n',
        'A concept with several broader parents can appear in more than one subject diagram.\n',
        '[Model and UI implications](taxonomy-v2.md#model-diagram) · '
        '[Editing guide](../../data/taxonomy-v2/README.md)\n',
        'Regenerate with `python3 data/taxonomy-v2/export_mermaid.py`.\n',
        '## Subject hierarchies\n',
    ]

    def label(row):
        text = f'{row["eticheta_ro"]}<br/>{row["id"]}'
        # Escape label text while keeping the one controlled line break.
        return html.escape(text, quote=True).replace('&lt;br/&gt;', '<br/>')

    def diagram(title, selected, group=None):
        chunks.append(f'### {title}\n')
        chunks.append('```mermaid\nflowchart TB')
        chosen = {r['id'] for r in selected}
        if group:
            chunks.append(f'    scheme["{html.escape(group, quote=True)}"]')
        for row in selected:
            ident = row['id']
            drawn.add(ident)
            chunks.append(f'    {node_ids[ident]}["{label(row)}"]')
            if group:
                chunks.append(f'    scheme --> {node_ids[ident]}')
        for row in selected:
            for parent in filter(None, row['mai_larg'].split('|')):
                if parent in chosen:
                    chunks.append(f'    {node_ids[parent]} --> {node_ids[row["id"]]}')
        chunks.append('```\n')

    subjects = [r for r in rows if r['schema'] == 'subiect']
    roots = [r for r in subjects if not r['mai_larg']]
    for root in roots:
        included = {root['id']}
        while True:
            expanded = included | {r['id'] for r in subjects if included.intersection(r['mai_larg'].split('|'))}
            if expanded == included:
                break
            included = expanded
        diagram(root['eticheta_ro'], [r for r in subjects if r['id'] in included])
    chunks.append('## Independent facets\n')
    chunks.append('The scheme node groups its concepts; it is not an additional concept or a broader-topic assertion.\n')
    for scheme, title in TITLES.items():
        selected = [r for r in rows if r['schema'] == scheme]
        if selected:
            diagram(title, selected, title)
    if drawn != set(by_id):
        raise SystemExit(f'Concepts missing from the diagrams: {sorted(set(by_id) - drawn)}')
    TARGET.write_text('\n'.join(chunks) + '\n', encoding='utf-8')
    print(f'Wrote {TARGET.relative_to(HERE.parents[1])}: {len(drawn)} concepts in {len(roots) + sum(any(r["schema"] == s for r in rows) for s in TITLES)} diagrams.')


if __name__ == '__main__':
    main()
